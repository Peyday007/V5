// Writes listings.csv and LISTINGS.md from catalog.mjs and the product manifests,
// and refuses anything over Etsy's limits (title ≤140, 13 tags ≤20 chars, ≤5 files ≤20MB, ≤20 photos).
//   node fast-cash/launch-2026-11-11/etsy/tools/build-listings.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORY, CATEGORY_ID, CATEGORY_FALLBACK, LICENCE, PRODUCTS, description } from './catalog.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const problems = [];

function filesFor(p) {
  const slugs = p.bundle ?? [p.slug];
  return slugs.map((s) => {
    const m = JSON.parse(fs.readFileSync(path.join(ROOT, 'products', s, 'manifest.json'), 'utf8'));
    return { name: m.pdf, rel: `products/${s}/${m.pdf}`, pages: m.pages, kb: Math.round(m.bytes / 1024), bytes: m.bytes, puzzles: m.puzzles, allValid: m.allValid };
  });
}

const rows = [];
let md = `# Etsy listings — paste-ready (generated ${new Date().toISOString().slice(0, 10)})

Generated by \`tools/build-listings.mjs\` from \`tools/catalog.mjs\`; every limit below is checked by the script.
Paths are relative to this folder (\`fast-cash/launch-2026-11-11/etsy/\`).

**Same for every listing**

| Field | Value |
|---|---|
| What type of item is it? | **Digital files** |
| Who made it? | **I did** |
| What is it? | **A finished product** |
| When was it made? | **2020 – 2026** |
| Category | **${CATEGORY}** (taxonomy id ${CATEGORY_ID}). If the category search does not offer it, use ${CATEGORY_FALLBACK}. |
| Quantity | **999** (digital: quantity never runs out; Etsy charges $0.20 per extra unit sold) |
| Renewal | **Automatic** |
| Shipping / processing | none — digital items have no shipping profile |
| Returns | No returns (digital) — set in shop policies; see SHOP-SETUP.md |
| Personalization | off |
| Attributes (if offered) | Holiday: Christmas (holiday products only) · Occasion: Christmas / Birthday · Theme: as fits; leave others blank |
| "How it's made" / AI question (if the form shows one) | The puzzles come from deterministic puzzle software (not an AI image/text generator); the listing copy and images were prepared with AI assistance. Pick the honest option that the form offers — if unsure, disclose AI assistance. |
| License | ${LICENCE} |

`;

for (const [i, p] of PRODUCTS.entries()) {
  const files = filesFor(p);
  const desc = description(p, files);
  const imgDir = path.join(ROOT, 'images', p.slug);
  const images = fs.readdirSync(imgDir).filter((f) => f.endsWith('.png')).sort();
  if (p.title.length > 140) problems.push(`${p.slug}: title ${p.title.length} chars`);
  if (p.tags.length !== 13) problems.push(`${p.slug}: ${p.tags.length} tags`);
  for (const t of p.tags) if (t.length > 20 || !/^[a-z0-9 ]+$/i.test(t)) problems.push(`${p.slug}: bad tag "${t}" (${t.length})`);
  if (new Set(p.tags).size !== p.tags.length) problems.push(`${p.slug}: duplicate tags`);
  if (files.length > 5) problems.push(`${p.slug}: ${files.length} files`);
  for (const f of files) if (f.bytes > 20 * 1024 * 1024) problems.push(`${p.slug}: ${f.name} over 20MB`);
  for (const f of files) if (!f.allValid) problems.push(`${p.slug}: ${f.name} has an invalid puzzle`);
  if (images.length < 5) problems.push(`${p.slug}: only ${images.length} images`);
  rows.push({
    listing_order: i + 1,
    slug: p.slug,
    title: p.title,
    price_usd: p.price.toFixed(2),
    quantity: 999,
    type: 'Digital files',
    who_made: 'I did',
    what_is_it: 'A finished product',
    when_made: '2020 - 2026',
    category: CATEGORY,
    taxonomy_id: CATEGORY_ID,
    tags: p.tags.join(','),
    materials: '',
    files: files.map((f) => f.rel).join(' | '),
    images_in_order: images.map((f) => `images/${p.slug}/${f}`).join(' | '),
    description: desc,
  });
  md += `---

## ${i + 1}. ${p.name} — $${p.price.toFixed(2)}

**Title** (${p.title.length}/140)

\`\`\`
${p.title}
\`\`\`

**Tags** (13, each ≤ 20 characters — paste one at a time or comma-separated)

\`\`\`
${p.tags.join(', ')}
\`\`\`

**Price:** $${p.price.toFixed(2)} · **Quantity:** 999 · **Type:** Digital files

**Files to upload** (${files.length}, all under 20 MB)

${files.map((f) => `- \`${f.rel}\` — ${f.pages} pages, ${f.kb} KB, ${f.puzzles} puzzles, all validator-passed`).join('\n')}

**Photos, in this order** (first = thumbnail)

${images.map((f, k) => `${k + 1}. \`images/${p.slug}/${f}\``).join('\n')}

**Description**

\`\`\`
${desc}
\`\`\`

`;
}

if (problems.length) {
  console.error('LIMIT PROBLEMS:\n' + problems.join('\n'));
  process.exit(1);
}

const cols = Object.keys(rows[0]);
const q = (v) => `"${String(v).replace(/"/g, '""')}"`;
fs.writeFileSync(path.join(ROOT, 'listings.csv'), [cols.join(','), ...rows.map((r) => cols.map((c) => q(r[c])).join(','))].join('\n') + '\n');
fs.writeFileSync(path.join(ROOT, 'LISTINGS.md'), md);
console.log(`OK ${rows.length} listings; titles ${rows.map((r) => r.title.length).join('/')}; prices ${rows.map((r) => r.price_usd).join('/')}`);
