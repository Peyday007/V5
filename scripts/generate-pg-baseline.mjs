/**
 * Generate the Postgres baseline migration from the real SQLite schema.
 *
 * The cloud schema has to be the same schema, not a schema somebody typed out
 * from memory of the same schema. So this applies the twelve SQLite migrations
 * to a throwaway file, reads back what SQLite actually created — every column
 * every ALTER added, in the order it added them — and translates that.
 *
 * Run it when the SQLite chain gains a migration whose shape the cloud baseline
 * should have had from the start; for an ordinary schema change after the cloud
 * chain exists, write a numbered pg-migration instead. Nothing runs this at
 * boot: the output is committed and reviewed like any other migration.
 *
 *   node scripts/generate-pg-baseline.mjs > server/db/pg-migrations/001_baseline.sql
 */
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('..', import.meta.url));
const MIGRATIONS = path.join(REPO, 'server', 'db', 'migrations');

/**
 * SQLite's types, in Postgres.
 *
 * TEXT stays text — including the columns that hold serialized JSON. Moving
 * those to jsonb would mean the driver handing back parsed objects where the
 * repositories expect strings, which is a change to a hundred call sites for no
 * behaviour anybody asked for. It is a deliberate, reversible choice: a later
 * migration can convert a column and its mapper together.
 */
const TYPES = {
  TEXT: 'text',
  INTEGER: 'integer',
  REAL: 'double precision',
  BLOB: 'bytea',
  NUMERIC: 'numeric',
};

function buildSchema() {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'brain-pg-')), 'schema.db');
  const db = new DatabaseSync(file);
  for (const name of fs.readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort()) {
    db.exec(fs.readFileSync(path.join(MIGRATIONS, name), 'utf8'));
  }
  const objects = db
    .prepare(
      `SELECT type, name, tbl_name, sql FROM sqlite_master
        WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
        ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name`,
    )
    .all();
  const columns = new Map();
  for (const object of objects) {
    if (object.type !== 'table') continue;
    columns.set(
      object.name,
      db.prepare(`PRAGMA table_info(${object.name})`).all(),
    );
  }
  const foreignKeys = new Map();
  for (const name of columns.keys()) {
    foreignKeys.set(name, db.prepare(`PRAGMA foreign_key_list(${name})`).all());
  }
  db.close();
  return { objects, columns, foreignKeys };
}

/** The CHECK constraints, lifted verbatim — there are few and they are simple. */
function checksFor(sql) {
  const found = [];
  const re = /CHECK\s*(\([^;]*?\))\s*(?:,|\)\s*;?\s*$)/gis;
  let match;
  while ((match = re.exec(sql)) !== null) found.push(match[1].trim());
  return found;
}

function compositePrimaryKey(sql) {
  const match = /PRIMARY KEY\s*\(([^)]*,[^)]*)\)/i.exec(sql);
  return match ? match[1].split(',').map((part) => part.trim()) : null;
}

function tableSql(name, columns, originalSql) {
  const lines = [];
  const composite = compositePrimaryKey(originalSql);

  for (const column of columns) {
    const type = TYPES[column.type.toUpperCase()] ?? 'text';
    let line = `  ${column.name.padEnd(24)} ${type}`;
    // A single-column primary key is declared inline, exactly as SQLite has it.
    if (column.pk === 1 && !composite) line += ' PRIMARY KEY';
    if (column.notnull === 1 && !(column.pk === 1 && !composite)) line += ' NOT NULL';
    if (column.dflt_value !== null && column.dflt_value !== undefined) {
      line += ` DEFAULT ${column.dflt_value}`;
    }
    lines.push(line);
  }

  // Every table gets the row counter that stands in for SQLite's rowid, which
  // thirty-odd queries use to make `ORDER BY created_at, rowid` a total order.
  // BY DEFAULT rather than ALWAYS so the cloud migrator can carry the original
  // insertion order across instead of inventing a new one.
  lines.push(`  ${'seq'.padEnd(24)} bigint GENERATED BY DEFAULT AS IDENTITY`);

  if (composite) lines.push(`  PRIMARY KEY (${composite.join(', ')})`);

  for (const check of checksFor(originalSql)) lines.push(`  CHECK ${check}`);

  return `CREATE TABLE ${name} (\n${lines.join(',\n')}\n);`;
}

/** Indexes need only the identifier quoting fixed; the rest is standard. */
function indexSql(sql) {
  return `${sql.replace(/\s+/g, ' ').trim()};`;
}

function main() {
  const { objects, columns, foreignKeys } = buildSchema();
  const out = [];

  out.push('-- ---------------------------------------------------------------------------');
  out.push('-- CLOUD BASELINE');
  out.push('--');
  out.push('-- The same schema the local chain arrives at after its twelve migrations,');
  out.push('-- expressed once for Postgres. It is generated from the SQLite schema rather');
  out.push('-- than written beside it (scripts/generate-pg-baseline.mjs), so the two cannot');
  out.push('-- drift into describing different things.');
  out.push('--');
  out.push('-- Four deliberate differences, and no others:');
  out.push('--');
  out.push('--   * every table carries `seq`, an identity column standing in for SQLite\'s');
  out.push('--     rowid. Thirty-odd queries order by it to break ties on equal timestamps,');
  out.push('--     and without it those orderings would be arbitrary rather than stable.');
  out.push('--   * columns holding serialized JSON stay `text`. jsonb would have the driver');
  out.push('--     return parsed objects where every repository expects a string; converting');
  out.push('--     a column and its mapper together is a later, deliberate migration.');
  out.push('--   * timestamps stay `text`, holding the same ISO-8601 UTC strings SQLite');
  out.push('--     holds. A timestamptz would re-interpret them on the way in and out, and');
  out.push('--     the point of this schema is that the values survive unchanged.');
  out.push('--   * a `nocase` collation is defined, so the three queries that compare a');
  out.push('--     canonical name case-insensitively read identically on both backends.');
  out.push('--     SQLite has `COLLATE NOCASE` built in; Postgres needs the collation to');
  out.push('--     exist, and a nondeterministic ICU one at strength level 2 is what gives');
  out.push('--     the same answer. Defining it here is what lets the repositories stay');
  out.push("--     free of `if (dialect === ...)`.");
  out.push('-- ---------------------------------------------------------------------------');
  out.push('');
  out.push('-- Must exist before any table that might reference it, and before the first');
  out.push('-- query that uses it.');
  out.push('CREATE COLLATION IF NOT EXISTS nocase (');
  out.push('  provider = icu,');
  out.push("  locale = 'und-u-ks-level2',");
  out.push('  deterministic = false');
  out.push(');');
  out.push('');

  for (const object of objects) {
    if (object.type !== 'table') continue;
    if (object.name === 'schema_migrations') continue;
    out.push(tableSql(object.name, columns.get(object.name), object.sql));
    out.push('');
  }

  // Foreign keys come after every table exists. SQLite resolves a reference to
  // a table declared later; Postgres does not, and reordering the tables by
  // hand would put the schema's shape at the mercy of alphabetical accident.
  out.push('-- Referential integrity, added once every table exists.');
  out.push('--');
  out.push('-- DEFERRABLE INITIALLY IMMEDIATE: checked per statement exactly as before,');
  out.push('-- so ordinary operation is unchanged and a broken reference still fails at');
  out.push('-- the statement that made it. What it adds is that a bulk loader may say');
  out.push('-- SET CONSTRAINTS ALL DEFERRED inside its own transaction — which the cloud');
  out.push('-- migration does, because this schema has self-references and cycles');
  out.push('-- (a run points at a document, a document at its parent, an orchestration');
  out.push('-- at an audit) and no table ordering exists that satisfies them all.');
  for (const object of objects) {
    if (object.type !== 'table') continue;
    if (object.name === 'schema_migrations') continue;
    const keys = foreignKeys.get(object.name) ?? [];
    // PRAGMA reports them newest-first; declaring them in source order keeps a
    // regenerated file from churning against the committed one.
    for (const fk of [...keys].reverse()) {
      const onDelete =
        fk.on_delete && fk.on_delete !== 'NO ACTION' ? ` ON DELETE ${fk.on_delete}` : '';
      out.push(
        `ALTER TABLE ${object.name} ADD CONSTRAINT ${object.name}_${fk.from}_fkey ` +
          `FOREIGN KEY (${fk.from}) REFERENCES ${fk.table}(${fk.to})${onDelete} ` +
          `DEFERRABLE INITIALLY IMMEDIATE;`,
      );
    }
  }
  out.push('');

  out.push('-- Indexes, exactly as the local chain declares them.');
  for (const object of objects) {
    if (object.type !== 'index') continue;
    out.push(indexSql(object.sql));
  }
  out.push('');

  process.stdout.write(`${out.join('\n')}\n`);
}

main();
